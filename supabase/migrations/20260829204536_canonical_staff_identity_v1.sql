-- Discover the known repairs from durable evidence. Current PINs and UUIDs are
-- deliberately not embedded in the migration: users.id/current pin are read
-- under lock, Bujar's retired PIN is proven by the preserved backup row, and
-- Blerim's oldest PIN is proven by its device history.
do $canonical_staff_repair$
declare
  v_actor public.users%rowtype;
  v_bujar public.users%rowtype;
  v_blerim public.users%rowtype;
  v_blerim_source public.users%rowtype;
  v_bujar_id uuid;
  v_blerim_id uuid;
  v_blerim_source_id uuid;
  v_count integer;
  v_bujar_retired_pin constant text := '5555';
  v_blerim_retired_pin constant text := '6666';
  v_blerim_device_pin constant text := '8888';
begin
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('staff_identity_pin_registry_v1',0)
  );
  select pg_catalog.count(*) into v_count
  from public.users u
  where u.is_active is true and u.is_master is true
    and pg_catalog.upper(coalesce(u.role,'')) in (
      'ADMIN','ADMIN_MASTER','OWNER','PRONAR','SUPERADMIN','MASTER','MASTER USER','MASTER_USER'
    );
  if v_count<>1 then raise exception 'STAFF_REPAIR_MANAGER_NOT_UNIQUE:%',v_count; end if;
  select * into v_actor
  from public.users u
  where u.is_active is true and u.is_master is true
    and pg_catalog.upper(coalesce(u.role,'')) in (
      'ADMIN','ADMIN_MASTER','OWNER','PRONAR','SUPERADMIN','MASTER','MASTER USER','MASTER_USER'
    )
  for update;

  select pg_catalog.count(*) into v_count
  from public.backup_bujar_oruqi_sleeping_20260614_v2 b
  join public.users u on u.id=b.id
  where b.pin=v_bujar_retired_pin and u.pin<>b.pin and u.is_active is true
    and private.staff_normalize_name_v1(u.name)=private.staff_normalize_name_v1(b.name)
    and pg_catalog.upper(pg_catalog.btrim(coalesce(u.role,'')))
      =pg_catalog.upper(pg_catalog.btrim(coalesce(b.role,'')));
  if v_count<>1 then raise exception 'STAFF_REPAIR_BUJAR_BACKUP_PROOF_FAILED:%',v_count; end if;
  select u.* into v_bujar
  from public.backup_bujar_oruqi_sleeping_20260614_v2 b
  join public.users u on u.id=b.id
  where b.pin=v_bujar_retired_pin and u.pin<>b.pin and u.is_active is true
    and private.staff_normalize_name_v1(u.name)=private.staff_normalize_name_v1(b.name)
    and pg_catalog.upper(pg_catalog.btrim(coalesce(u.role,'')))
      =pg_catalog.upper(pg_catalog.btrim(coalesce(b.role,'')))
  for update of u;
  v_bujar_id := v_bujar.id;

  select pg_catalog.count(*) into v_count
  from public.users u
  where u.pin=v_blerim_retired_pin and u.is_active is false;
  if v_count>1 then raise exception 'STAFF_REPAIR_BLERIM_SOURCE_NOT_UNIQUE:%',v_count; end if;

  if v_count=1 then
    select * into v_blerim_source
    from public.users u
    where u.pin=v_blerim_retired_pin and u.is_active is false
    for update;
    v_blerim_source_id := v_blerim_source.id;

    select pg_catalog.count(*) into v_count
    from public.users u
    where u.id<>v_blerim_source.id and u.is_active is true
      and private.staff_normalize_name_v1(u.name)=private.staff_normalize_name_v1(v_blerim_source.name)
      and pg_catalog.upper(pg_catalog.btrim(coalesce(u.role,'')))
        =pg_catalog.upper(pg_catalog.btrim(coalesce(v_blerim_source.role,'')));
    if v_count<>1 then raise exception 'STAFF_REPAIR_BLERIM_CANONICAL_NOT_UNIQUE:%',v_count; end if;
    select * into v_blerim
    from public.users u
    where u.id<>v_blerim_source.id and u.is_active is true
      and private.staff_normalize_name_v1(u.name)=private.staff_normalize_name_v1(v_blerim_source.name)
      and pg_catalog.upper(pg_catalog.btrim(coalesce(u.role,'')))
        =pg_catalog.upper(pg_catalog.btrim(coalesce(v_blerim_source.role,'')))
    for update;

    if not exists(
      select 1
      from public.tepiha_device_approvals a
      join public.tepiha_user_devices d
        on d.user_id=v_blerim_source.id and d.device_id=a.device_id
      where a.pin=v_blerim_device_pin and d.requested_pin=v_blerim_device_pin
    ) then raise exception 'STAFF_REPAIR_BLERIM_DEVICE_HISTORY_PROOF_FAILED'; end if;
  else
    select a.source_user_id into v_blerim_source_id
    from private.staff_pin_aliases a
    where a.alias_pin=v_blerim_retired_pin;
    if v_blerim_source_id is null then raise exception 'STAFF_REPAIR_BLERIM_SOURCE_PROOF_MISSING'; end if;

    select u.* into v_blerim
    from private.staff_pin_aliases a
    join public.users u on u.id=a.canonical_user_id
    where a.alias_pin=v_blerim_retired_pin and u.is_active is true;
    if not found then raise exception 'STAFF_REPAIR_BLERIM_CANONICAL_ALIAS_MISSING'; end if;
    if not exists(
      select 1 from private.staff_pin_aliases a
      where a.alias_pin=v_blerim_device_pin and a.canonical_user_id=v_blerim.id
    ) then raise exception 'STAFF_REPAIR_BLERIM_DEVICE_ALIAS_MISSING'; end if;
    if not exists(
      select 1 from private.staff_identity_merge_log l
      where l.idempotency_key='CANONICAL_STAFF_IDENTITY_V1:BLERIM:DUPLICATE_MERGE'
        and l.source_user_id=v_blerim_source_id and l.canonical_user_id=v_blerim.id
    ) then raise exception 'STAFF_REPAIR_BLERIM_MERGE_PROOF_MISSING'; end if;
  end if;

  if v_bujar.pin=any(array[v_bujar_retired_pin,v_blerim_retired_pin,v_blerim_device_pin])
     or v_blerim.pin=any(array[v_bujar_retired_pin,v_blerim_retired_pin,v_blerim_device_pin]) then
    raise exception 'STAFF_REPAIR_CURRENT_PIN_IS_RETIRED';
  end if;
  v_blerim_id := v_blerim.id;

  perform public.merge_staff_identity_v1(
    v_actor.pin,v_bujar_id,null,v_bujar.pin,null,array[v_bujar_retired_pin]::text[],
    'CANONICAL_STAFF_IDENTITY_V1:BUJAR:RETIRED_PIN_HISTORY'
  );
  perform public.merge_staff_identity_v1(
    v_actor.pin,v_blerim_id,v_blerim_source_id,v_blerim.pin,v_blerim_retired_pin,
    array[v_blerim_retired_pin,v_blerim_device_pin]::text[],
    'CANONICAL_STAFF_IDENTITY_V1:BLERIM:DUPLICATE_MERGE'
  );

  select * into v_bujar from public.users where id=v_bujar_id;
  select * into v_blerim from public.users where id=v_blerim_id;
  if v_bujar.is_active is not true or v_blerim.is_active is not true then
    raise exception 'STAFF_POSTCHECK_CANONICAL_USER_INACTIVE';
  end if;
  if exists(
    select 1 from public.users
    where pin=any(array[v_bujar_retired_pin,v_blerim_retired_pin,v_blerim_device_pin])
  ) then raise exception 'STAFF_POSTCHECK_RETIRED_PIN_STILL_CURRENT'; end if;
  if exists(select 1 from public.users where id=v_blerim_source_id) then
    raise exception 'STAFF_POSTCHECK_BLERIM_SOURCE_STILL_EXISTS';
  end if;
  if (select pg_catalog.count(*) from public.users u
      where private.staff_normalize_name_v1(u.name)=private.staff_normalize_name_v1(v_bujar.name))<>1
     or (select pg_catalog.count(*) from public.users u
      where private.staff_normalize_name_v1(u.name)=private.staff_normalize_name_v1(v_blerim.name))<>1 then
    raise exception 'STAFF_POSTCHECK_NORMALIZED_NAME_NOT_UNIQUE';
  end if;
  if not exists(
    select 1 from private.staff_pin_aliases a
    where a.alias_pin=v_bujar_retired_pin and a.canonical_user_id=v_bujar.id
      and a.current_pin_snapshot=v_bujar.pin
  ) or (select pg_catalog.count(*) from private.staff_pin_aliases a
        where a.alias_pin in (v_blerim_retired_pin,v_blerim_device_pin)
          and a.canonical_user_id=v_blerim.id and a.current_pin_snapshot=v_blerim.pin)<>2 then
    raise exception 'STAFF_POSTCHECK_ALIAS_MAPPING_FAILED';
  end if;

  if exists(
    select 1 from public.tepiha_user_devices d
    where d.user_id=v_blerim_source_id
      or d.requested_pin=any(array[v_bujar_retired_pin,v_blerim_retired_pin,v_blerim_device_pin])
  ) then raise exception 'STAFF_POSTCHECK_DEVICE_IDENTITY_FAILED'; end if;
  if exists(
    select 1 from public.tepiha_device_approvals a
    where a.pin=any(array[v_bujar_retired_pin,v_blerim_retired_pin,v_blerim_device_pin])
  ) then raise exception 'STAFF_POSTCHECK_DEVICE_APPROVAL_PIN_FAILED'; end if;
  if exists(
    select 1
    from public.tepiha_device_approvals a
    left join public.tepiha_user_devices d
      on d.device_id=a.device_id
     and d.user_id=case when a.pin=v_bujar.pin then v_bujar.id else v_blerim.id end
    where a.pin in (v_bujar.pin,v_blerim.pin)
      and a.approved is distinct from coalesce(d.is_approved,false)
  ) then raise exception 'STAFF_POSTCHECK_DEVICE_APPROVAL_ELEVATION'; end if;
  if exists(select 1 from public.payroll_month_close_items where worker_id=v_blerim_source_id)
     or exists(select 1 from public.worker_employment_terms where user_id=v_blerim_source_id) then
    raise exception 'STAFF_POSTCHECK_UUID_REFERENCE_FAILED';
  end if;

  if exists(
    select 1 from public.base_code_pool b
    where b.owner_id=any(array[v_bujar_retired_pin,v_blerim_retired_pin,v_blerim_device_pin])
       or b.reserved_by=any(array[v_bujar_retired_pin,v_blerim_retired_pin,v_blerim_device_pin])
       or b.used_by_pin=any(array[v_bujar_retired_pin,v_blerim_retired_pin,v_blerim_device_pin])
  ) then raise exception 'STAFF_POSTCHECK_BASE_POOL_IDENTITY_FAILED'; end if;
  if exists(
    select 1 from public.offline_code_leases l
    where l.owner_id=any(
      array[v_bujar_retired_pin,v_blerim_retired_pin,v_blerim_device_pin,v_blerim_source_id::text]
    )
  ) then raise exception 'STAFF_POSTCHECK_OFFLINE_LEASE_IDENTITY_FAILED'; end if;
  if exists(
    select 1 from public.transport_code_pool t
    where t.owner_id=any(
      array[v_bujar_retired_pin,v_blerim_retired_pin,v_blerim_device_pin,v_blerim_source_id::text]
    )
  ) then raise exception 'STAFF_POSTCHECK_TRANSPORT_POOL_IDENTITY_FAILED'; end if;

  if exists(
    select 1 from public.orders o
    where o.data is distinct from private.staff_identity_json_canonicalize_v1(
      o.data,array[v_bujar_retired_pin],v_bujar.pin,'{}'::text[],v_bujar.id::text
    ) or o.data is distinct from private.staff_identity_json_canonicalize_v1(
      o.data,array[v_blerim_retired_pin,v_blerim_device_pin],v_blerim.pin,
      array[v_blerim_source_id::text],v_blerim.id::text
    )
  ) then raise exception 'STAFF_POSTCHECK_ORDER_IDENTITY_FIELDS_FAILED'; end if;
  if exists(
    select 1 from public.transport_orders o
    where o.data is distinct from private.staff_identity_json_canonicalize_v1(
      o.data,array[v_bujar_retired_pin],v_bujar.pin,'{}'::text[],v_bujar.id::text
    ) or o.data is distinct from private.staff_identity_json_canonicalize_v1(
      o.data,array[v_blerim_retired_pin,v_blerim_device_pin],v_blerim.pin,
      array[v_blerim_source_id::text],v_blerim.id::text
    )
  ) then raise exception 'STAFF_POSTCHECK_TRANSPORT_IDENTITY_FIELDS_FAILED'; end if;

  if exists(
    select 1
    from (values ('anon'),('authenticated')) as r(role_name)
    cross join (values
      ('public.tepiha_user_devices'),('public.tepiha_device_approvals')
    ) as t(table_name)
    cross join (values ('SELECT'),('INSERT'),('UPDATE'),('DELETE')) as p(privilege_name)
    where pg_catalog.has_table_privilege(r.role_name,t.table_name,p.privilege_name)
  ) then raise exception 'STAFF_POSTCHECK_DEVICE_TABLE_ACL_FAILED'; end if;
  if exists(
    select 1 from public.users u
    where pg_catalog.btrim(coalesce(u.name,''))<>''
    group by private.staff_normalize_name_v1(u.name)
    having pg_catalog.count(*)>1
  ) then raise exception 'STAFF_POSTCHECK_ANY_NORMALIZED_NAME_DUPLICATE'; end if;
end;
$canonical_staff_repair$;

create unique index if not exists users_normalized_name_uq_v1
on public.users ((
  pg_catalog.lower(pg_catalog.regexp_replace(pg_catalog.btrim(coalesce(name,'')),'\s+',' ','g'))
))
where pg_catalog.btrim(coalesce(name,''))<>'';

