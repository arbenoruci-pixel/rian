create or replace function private.guard_staff_current_pin_reuse_v1()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('staff_identity_pin_registry_v1',0)
  );
  if tg_op = 'INSERT' then
    if exists (
      select 1 from private.staff_pin_aliases a
      where a.alias_pin = pg_catalog.btrim(new.pin)
    ) then raise exception 'STAFF_PIN_IS_RETIRED:%', new.pin; end if;
  elsif new.pin is distinct from old.pin then
    if exists (
      select 1 from private.staff_pin_aliases a
      where a.alias_pin = pg_catalog.btrim(new.pin)
    ) then raise exception 'STAFF_PIN_IS_RETIRED:%', new.pin; end if;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_guard_staff_current_pin_reuse_v1 on public.users;
create trigger trg_guard_staff_current_pin_reuse_v1
before insert or update of pin on public.users
for each row execute function private.guard_staff_current_pin_reuse_v1();

create or replace function private.staff_identity_json_canonicalize_v1(
  p_value jsonb,
  p_old_pins text[],
  p_new_pin text,
  p_old_user_ids text[] default '{}'::text[],
  p_new_transport_id text default null
)
returns jsonb
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_type text;
  v_key text;
  v_item jsonb;
  v_text text;
  v_result jsonb;
  v_pin_keys constant text[] := array[
    'actor_pin','accepted_by_pin','approved_by_pin','assigned_driver_pin','assigned_to_pin',
    'audited_by_pin','base_driver_notified_by','base_driver_notified_by_pin','beneficiary_pin',
    'brought_by_pin','cancelled_by_pin','changed_by_pin','closed_by_pin','completed_by_pin',
    'created_by_pin','decided_by_pin','delivered_by','delivered_by_pin','dispatch_pin',
    'driver_pin','finalized_by_pin','found_by','handed_by_pin','last_payment_by_pin','opened_by_pin',
    'paid_by_pin','pickup_confirmed_by_pin','posted_by_pin','prepaid_by_pin','ready_by_pin',
    'ready_note_by_pin','recovered_by_pin','released_by_pin','requested_pin','resolved_by_pin',
    'responsible_worker_pin','reviewed_by_pin','transport_pin','updated_by','updated_by_pin',
    'worker_pin','wrapped_by','by_pin','pin'
  ];
  v_id_keys constant text[] := array[
    'assigned_driver_id','cancelled_by_transport_id','delivered_by_transport_id','driver_id',
    'tid','transport_id','transport_user_id'
  ];
begin
  if p_value is null then return null; end if;
  v_type := pg_catalog.jsonb_typeof(p_value);

  if v_type = 'object' then
    v_result := '{}'::jsonb;
    for v_key, v_item in select key, value from pg_catalog.jsonb_each(p_value)
    loop
      if pg_catalog.jsonb_typeof(v_item) in ('string', 'number') then
        v_text := v_item #>> '{}';
        if v_key = any(v_pin_keys) and v_text = any(coalesce(p_old_pins, '{}'::text[])) then
          v_item := pg_catalog.to_jsonb(p_new_pin);
        elsif v_key = any(v_id_keys)
          and (
            v_text = any(coalesce(p_old_user_ids, '{}'::text[]))
            or (v_key in ('transport_id','tid') and v_text = any(coalesce(p_old_pins, '{}'::text[])))
          )
          and p_new_transport_id is not null then
          v_item := pg_catalog.to_jsonb(p_new_transport_id);
        end if;
      elsif pg_catalog.jsonb_typeof(v_item) in ('object', 'array') then
        v_item := private.staff_identity_json_canonicalize_v1(
          v_item, p_old_pins, p_new_pin, p_old_user_ids, p_new_transport_id
        );
      end if;
      v_result := v_result || pg_catalog.jsonb_build_object(v_key, v_item);
    end loop;
    return v_result;
  elsif v_type = 'array' then
    select coalesce(
      pg_catalog.jsonb_agg(
        private.staff_identity_json_canonicalize_v1(
          x.value, p_old_pins, p_new_pin, p_old_user_ids, p_new_transport_id
        ) order by x.ordinality
      ),
      '[]'::jsonb
    ) into v_result
    from pg_catalog.jsonb_array_elements(p_value) with ordinality as x(value, ordinality);
    return v_result;
  end if;

  return p_value;
end;
$$;

create or replace function private.staff_update_pin_column_if_present_v1(
  p_table_name text,
  p_column_name text,
  p_old_pins text[],
  p_new_pin text
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_table regclass;
  v_rows integer := 0;
  v_has_old boolean := false;
begin
  v_table := pg_catalog.to_regclass(p_table_name);
  if v_table is null then return 0; end if;

  if not exists (
    select 1
    from pg_catalog.pg_attribute a
    where a.attrelid = v_table
      and a.attname = p_column_name
      and a.attnum > 0
      and not a.attisdropped
  ) then
    return 0;
  end if;

  execute pg_catalog.format(
    'update %s set %I = $1 where %I = any($2)',
    v_table, p_column_name, p_column_name
  ) using p_new_pin, p_old_pins;
  get diagnostics v_rows = row_count;

  execute pg_catalog.format(
    'select exists(select 1 from %s where %I=any($1))',
    v_table,p_column_name
  ) into v_has_old using p_old_pins;
  if v_has_old then
    raise exception 'STAFF_STRUCTURED_PIN_POSTCHECK_FAILED:%.%',p_table_name,p_column_name;
  end if;
  return v_rows;
end;
$$;

create or replace function private.staff_financial_checksum_v1(p_pins text[])
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select pg_catalog.jsonb_build_object(
    'arka_created_count', (select pg_catalog.count(*) from public.arka_pending_payments p where p.created_by_pin = any(p_pins)),
    'arka_created_amount', (select pg_catalog.round(coalesce(pg_catalog.sum(p.amount),0),2) from public.arka_pending_payments p where p.created_by_pin = any(p_pins)),
    'handoff_count', (select pg_catalog.count(*) from public.cash_handoffs h where h.worker_pin = any(p_pins)),
    'handoff_amount', (select pg_catalog.round(coalesce(pg_catalog.sum(h.amount),0),2) from public.cash_handoffs h where h.worker_pin = any(p_pins)),
    'bonus_count', (select pg_catalog.count(*) from public.base_ready_bonuses b where b.worker_pin = any(p_pins)),
    'bonus_amount', (select pg_catalog.round(coalesce(pg_catalog.sum(b.amount),0),2) from public.base_ready_bonuses b where b.worker_pin = any(p_pins)),
    'payroll_count', (select pg_catalog.count(*) from public.payroll_month_close_items i where i.worker_pin = any(p_pins)),
    'payroll_net', (select pg_catalog.round(coalesce(pg_catalog.sum(i.net_pay),0),2) from public.payroll_month_close_items i where i.worker_pin = any(p_pins)),
    'transport_batch_count', (select pg_catalog.count(*) from public.transport_payment_batches b where b.created_by_pin = any(p_pins)),
    'transport_batch_amount', (select pg_catalog.round(coalesce(pg_catalog.sum(b.amount_applied),0),2) from public.transport_payment_batches b where b.created_by_pin = any(p_pins))
  );
$$;

create or replace function private.canonicalize_staff_history_v1(
  p_canonical_user_id uuid,
  p_old_pins text[],
  p_new_pin text,
  p_old_user_ids uuid[] default '{}'::uuid[]
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_pair record;
  v_rows integer := 0;
  v_total_rows integer := 0;
  v_order_rows integer := 0;
  v_transport_rows integer := 0;
  v_old_id_texts text[] := '{}'::text[];
  v_transport_id text;
  v_canonical_role text;
  v_approval public.tepiha_device_approvals%rowtype;
  v_current_approval public.tepiha_device_approvals%rowtype;
  v_authoritative_device public.tepiha_user_devices%rowtype;
  v_has_current_approval boolean;
  v_has_authoritative_device boolean;
  v_prev_maintenance text := pg_catalog.current_setting('tepiha.finance_maintenance', true);
begin
  if p_canonical_user_id is null then raise exception 'STAFF_CANONICAL_USER_ID_REQUIRED'; end if;
  if p_new_pin is null or pg_catalog.btrim(p_new_pin) = '' then raise exception 'STAFF_NEW_PIN_REQUIRED'; end if;

  -- UUID identity keys always converge on users.id. transport_id/tid are
  -- compatibility aliases and must never select a second durable identity.
  select u.id::text,u.role
  into v_transport_id,v_canonical_role
  from public.users u
  where u.id = p_canonical_user_id;
  if not found then raise exception 'STAFF_CANONICAL_USER_NOT_FOUND:%', p_canonical_user_id; end if;

  select coalesce(pg_catalog.array_agg(x::text), '{}'::text[])
  into v_old_id_texts
  from pg_catalog.unnest(coalesce(p_old_user_ids, '{}'::uuid[])) as x;

  perform pg_catalog.set_config('tepiha.finance_maintenance', 'on', true);

  -- BASE allocator rows have lifecycle meaning. Expired, unreferenced retired-
  -- identity reservations are released (never moved into the current PIN's
  -- quota); terminal USED ownership is historical identity and is canonicalized.
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtext('tepiha_pranimi_code_allocator_v39_1')
  );

  update public.offline_code_leases l
  set status='expired', released_at=coalesce(l.released_at,pg_catalog.now()),
      updated_at=pg_catalog.now(),
      metadata=coalesce(l.metadata,'{}'::jsonb)
        || pg_catalog.jsonb_build_object('expired_reason','retired_staff_pool_release')
  where l.scope='base'
    and l.status in ('available','assigned')
    and l.expires_at is not null
    and l.expires_at<=pg_catalog.now()
    and exists(
      select 1 from public.base_code_pool b
      where b.code::text=l.code
        and b.status='reserved'
        and (b.owner_id=any(p_old_pins) or b.reserved_by=any(p_old_pins))
        and b.lease_expires_at is not null
        and b.lease_expires_at <= pg_catalog.now()
        and not exists(
          select 1 from public.offline_code_leases active_l
          where active_l.scope='base' and active_l.code=b.code::text
            and active_l.status in ('available','assigned')
            and (active_l.expires_at is null or active_l.expires_at>pg_catalog.now())
        )
        and not exists(select 1 from public.orders o where o.code::text=b.code::text)
        and not exists(select 1 from public.clients c where c.code::text=b.code::text)
    );
  get diagnostics v_rows = row_count;
  v_total_rows := v_total_rows + v_rows;

  update public.base_code_pool b
  set status='available', owner_id='', reserved_by=null, reserved_at=null,
      lease_expires_at=null, draft_session_id=null,
      draft_has_meaningful_work=false
  where b.status='reserved'
    and (b.owner_id=any(p_old_pins) or b.reserved_by=any(p_old_pins))
    and b.lease_expires_at is not null
    and b.lease_expires_at <= pg_catalog.now()
    and not exists(
      select 1 from public.offline_code_leases active_l
      where active_l.scope='base' and active_l.code=b.code::text
        and active_l.status in ('available','assigned')
        and (active_l.expires_at is null or active_l.expires_at>pg_catalog.now())
    )
    and not exists(select 1 from public.orders o where o.code::text=b.code::text)
    and not exists(select 1 from public.clients c where c.code::text=b.code::text);
  get diagnostics v_rows = row_count;
  v_total_rows := v_total_rows + v_rows;

  if exists(
    select 1 from public.base_code_pool b
    where b.status='reserved'
      and (b.owner_id=any(p_old_pins) or b.reserved_by=any(p_old_pins))
  ) then raise exception 'STAFF_BASE_RESERVATION_LIFECYCLE_CONFLICT'; end if;

  update public.base_code_pool b
  set owner_id=p_new_pin
  where b.status='used' and b.owner_id=any(p_old_pins);
  get diagnostics v_rows = row_count;
  v_total_rows := v_total_rows + v_rows;

  update public.base_code_pool b
  set owner_id=''
  where b.status='available' and b.owner_id=any(p_old_pins);
  get diagnostics v_rows = row_count;
  v_total_rows := v_total_rows + v_rows;

  -- Expired offline leases are terminalized before their identity snapshot is
  -- canonicalized. Live leases were rejected by merge_staff_identity_v1.
  update public.offline_code_leases l
  set status='expired', released_at=coalesce(l.released_at,pg_catalog.now()),
      updated_at=pg_catalog.now(),
      metadata=coalesce(l.metadata,'{}'::jsonb)
        || pg_catalog.jsonb_build_object('expired_reason','staff_identity_retired')
  where l.owner_id=any(p_old_pins || v_old_id_texts)
    and l.status in ('available','assigned')
    and l.expires_at <= pg_catalog.now();
  get diagnostics v_rows = row_count;
  v_total_rows := v_total_rows + v_rows;

  update public.offline_code_leases l
  set owner_id=case when l.scope='transport' then p_canonical_user_id::text else p_new_pin end,
      updated_at=pg_catalog.now()
  where l.owner_id=any(p_old_pins || v_old_id_texts)
    and not (
      l.status in ('available','assigned')
      and (l.expires_at is null or l.expires_at>pg_catalog.now())
    );
  get diagnostics v_rows = row_count;
  v_total_rows := v_total_rows + v_rows;

  if exists(
    select 1 from public.transport_code_pool t
    where t.owner_id=any(p_old_pins || v_old_id_texts) and t.status<>'used'
  ) then raise exception 'STAFF_TRANSPORT_CODE_LIFECYCLE_CONFLICT'; end if;

  update public.transport_code_pool t
  set owner_id=p_canonical_user_id::text
  where t.status='used' and t.owner_id=any(p_old_pins || v_old_id_texts);
  get diagnostics v_rows = row_count;
  v_total_rows := v_total_rows + v_rows;

  for v_pair in
    select * from (values
      ('public.arka_advance_budget_links','posted_by_pin'),
      ('public.arka_cycles','opened_by_pin'),
      ('public.arka_cycles','closed_by_pin'),
      ('public.arka_daily_close_items','worker_pin'),
      ('public.arka_expense_decisions','driver_pin'),
      ('public.arka_expense_decisions','beneficiary_pin'),
      ('public.arka_expense_decisions','decided_by_pin'),
      ('public.arka_expense_decisions','cancelled_by_pin'),
      ('public.arka_expense_decisions','finalized_by_pin'),
      ('public.arka_payment_exclusions','created_by_pin'),
      ('public.arka_payment_exclusions','cancelled_by_pin'),
      ('public.arka_pending_payments','created_by_pin'),
      ('public.arka_pending_payments','approved_by_pin'),
      ('public.arka_pending_payments','handed_by_pin'),
      ('public.base_code_pool','used_by_pin'),
      ('public.base_ready_bonus_config','updated_by_pin'),
      ('public.base_ready_bonuses','worker_pin'),
      ('public.cash_handoff_expense_decisions','driver_pin'),
      ('public.cash_handoff_expense_decisions','beneficiary_pin'),
      ('public.cash_handoff_expense_decisions','decided_by_pin'),
      ('public.cash_handoff_expense_decisions','cancelled_by_pin'),
      ('public.cash_handoff_items','released_by_pin'),
      ('public.cash_handoffs','worker_pin'),
      ('public.cash_handoffs','dispatch_pin'),
      ('public.company_budget_ledger','created_by_pin'),
      ('public.company_budget_ledger','approved_by_pin'),
      ('public.company_budget_moves','created_by_pin'),
      ('public.company_budget_moves','worker_pin'),
      ('public.company_budget_moves','accepted_by_pin'),
      ('public.company_fixed_expenses','created_by_pin'),
      ('public.manual_budget_adjustments','created_by_pin'),
      ('public.manual_budget_adjustments','cancelled_by_pin'),
      ('public.payroll_month_close_items','worker_pin'),
      ('public.payroll_month_close_items','accepted_by_worker_pin'),
      ('public.payroll_month_closes','created_by_pin'),
      ('public.tepiha_user_devices','requested_pin'),
      ('public.transport_delivery_events','actor_pin'),
      ('public.transport_payment_batches','created_by_pin'),
      ('public.transport_receivables','created_by_pin'),
      ('public.users','pay_updated_by_pin'),
      ('public.worker_compensation_audit','worker_pin'),
      ('public.worker_compensation_audit','changed_by_pin'),
      ('public.worker_employment_terms','created_by_pin')
    ) as x(table_name, column_name)
  loop
    v_rows := private.staff_update_pin_column_if_present_v1(
      v_pair.table_name, v_pair.column_name, p_old_pins, p_new_pin
    );
    v_total_rows := v_total_rows + v_rows;
  end loop;

  -- The UUID-linked user-device row is authoritative. Mirror approvals are
  -- re-keyed without carrying approval from a retired PIN: a missing or false
  -- authoritative link becomes false, while a true link remains true. Existing
  -- (current PIN, device) rows are reconciled before deleting the duplicate.
  for v_approval in
    select a.*
    from public.tepiha_device_approvals a
    where a.pin=any(p_old_pins)
    order by a.id
    for update
  loop
    select * into v_authoritative_device
    from public.tepiha_user_devices d
    where d.user_id=p_canonical_user_id and d.device_id=v_approval.device_id
    order by d.created_at desc
    limit 1;
    v_has_authoritative_device := found;

    select * into v_current_approval
    from public.tepiha_device_approvals a
    where a.pin=p_new_pin and a.device_id=v_approval.device_id
    limit 1
    for update;
    v_has_current_approval := found;

    if v_has_current_approval then
      update public.tepiha_device_approvals a
      set approved=case when v_has_authoritative_device
                          then v_authoritative_device.is_approved else false end,
          approved_at=case
            when v_has_authoritative_device and v_authoritative_device.is_approved
              then coalesce(v_authoritative_device.approved_at,a.approved_at,v_approval.approved_at)
            else null end,
          approved_by=case
            when v_has_authoritative_device and v_authoritative_device.is_approved
              then coalesce(v_authoritative_device.approved_by,a.approved_by,v_approval.approved_by)
            else null end,
          role=coalesce(
            case when v_has_authoritative_device then v_authoritative_device.requested_role end,
            a.role,v_approval.role,v_canonical_role
          ),
          label=coalesce(a.label,v_approval.label),
          last_seen_at=greatest(a.last_seen_at,v_approval.last_seen_at)
      where a.id=v_current_approval.id;
      delete from public.tepiha_device_approvals where id=v_approval.id;
      v_total_rows := v_total_rows + 2;
    else
      update public.tepiha_device_approvals a
      set pin=p_new_pin,
          approved=case when v_has_authoritative_device
                          then v_authoritative_device.is_approved else false end,
          approved_at=case
            when v_has_authoritative_device and v_authoritative_device.is_approved
              then coalesce(v_authoritative_device.approved_at,a.approved_at)
            else null end,
          approved_by=case
            when v_has_authoritative_device and v_authoritative_device.is_approved
              then coalesce(v_authoritative_device.approved_by,a.approved_by)
            else null end,
          role=coalesce(
            case when v_has_authoritative_device then v_authoritative_device.requested_role end,
            a.role,v_canonical_role
          )
      where a.id=v_approval.id;
      v_total_rows := v_total_rows + 1;
    end if;
  end loop;

  -- Exact structured JSON identity keys only. The recursive walker never
  -- rewrites notes, phones, client data, free text, or idempotency keys.
  --
  -- These are maintenance-only identity rewrites, not business transitions.
  -- Normal order triggers would otherwise upsert clients, renew offline code
  -- leases, recalculate bonuses, capture locations and alter updated_at. Require
  -- every user trigger to be enabled before entry, then suppress USER triggers
  -- only for the two controlled JSON updates. Constraint triggers stay active.
  -- The exception block restores the known-good trigger state before rethrowing;
  -- the surrounding transaction also rolls back every write on failure.
  if exists (
    select 1 from pg_catalog.pg_trigger t
    where t.tgrelid in ('public.orders'::pg_catalog.regclass,
                        'public.transport_orders'::pg_catalog.regclass)
      and not t.tgisinternal and t.tgenabled <> 'O'
  ) then raise exception 'STAFF_ORDER_TRIGGER_STATE_UNSAFE'; end if;

  begin
    execute 'alter table public.orders disable trigger user';
    execute 'alter table public.transport_orders disable trigger user';

    with candidates as materialized (
      select o.id,
        private.staff_identity_json_canonicalize_v1(
          o.data, p_old_pins, p_new_pin, v_old_id_texts, v_transport_id
        ) as next_data
      from public.orders o
    )
    update public.orders o
    set data = c.next_data
    from candidates c
    where o.id = c.id and o.data is distinct from c.next_data;
    get diagnostics v_order_rows = row_count;

    with candidates as materialized (
      select o.id,
        private.staff_identity_json_canonicalize_v1(
          o.data, p_old_pins, p_new_pin, v_old_id_texts, v_transport_id
        ) as next_data
      from public.transport_orders o
    )
    update public.transport_orders o
    set data = c.next_data
    from candidates c
    where o.id = c.id and o.data is distinct from c.next_data;
    get diagnostics v_transport_rows = row_count;

    execute 'alter table public.transport_orders enable trigger user';
    execute 'alter table public.orders enable trigger user';
  exception when others then
    execute 'alter table public.transport_orders enable trigger user';
    execute 'alter table public.orders enable trigger user';
    raise;
  end;

  if p_old_user_ids is not null and pg_catalog.cardinality(p_old_user_ids) > 0 then
    update public.payroll_month_close_items
    set worker_id = p_canonical_user_id
    where worker_id = any(p_old_user_ids);
    get diagnostics v_rows = row_count;
    v_total_rows := v_total_rows + v_rows;
  end if;

  perform pg_catalog.set_config(
    'tepiha.finance_maintenance', coalesce(v_prev_maintenance, ''), true
  );

  return pg_catalog.jsonb_build_object(
    'structured_rows', v_total_rows,
    'order_json_rows', v_order_rows,
    'transport_json_rows', v_transport_rows
  );
end;
$$;

