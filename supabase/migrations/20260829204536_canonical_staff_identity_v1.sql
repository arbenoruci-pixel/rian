-- Canonical staff identity V1.
--
-- Invariants:
--   * public.users.id is the durable staff identity; a PIN is a mutable credential.
--   * retired PINs never become independent users and are never accepted by login.
--   * historical finance/order rows keep their row IDs, amounts, notes and
--     idempotency keys; only explicitly allow-listed identity fields are canonicalized.
--   * allocator owner fields are lifecycle tokens: expired reservations are
--     released, while terminal USED ownership is canonicalized deliberately.
--   * every merge/save operation is serialized and idempotent.

create schema if not exists private;

alter table public.users
  add column if not exists updated_at timestamptz not null default pg_catalog.now();

create or replace function private.set_staff_user_updated_at_v1()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.updated_at is not distinct from old.updated_at then
    new.updated_at := pg_catalog.clock_timestamp();
  end if;
  return new;
end;
$$;

drop trigger if exists trg_staff_user_updated_at_v1 on public.users;
create trigger trg_staff_user_updated_at_v1
before update on public.users
for each row execute function private.set_staff_user_updated_at_v1();

create table if not exists private.staff_pin_aliases (
  alias_pin text primary key,
  canonical_user_id uuid not null references public.users(id) on delete restrict,
  current_pin_snapshot text not null,
  source_user_id uuid null,
