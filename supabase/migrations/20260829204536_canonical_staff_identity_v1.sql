create or replace function public.save_staff_identity_v1(
  p_actor_pin text,
  p_action text,
  p_user_id uuid default null,
  p_name text default null,
  p_role text default null,
  p_pin text default null,
  p_is_active boolean default null,
  p_patch jsonb default '{}'::jsonb,
  p_reactivate_user_id uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor public.users%rowtype;
  v_before public.users%rowtype;
  v_after public.users%rowtype;
  v_existing private.staff_identity_merge_log%rowtype;
  v_action text := pg_catalog.upper(pg_catalog.btrim(coalesce(p_action,'')));
  v_name text := pg_catalog.btrim(coalesce(p_name,''));
  v_role text := pg_catalog.upper(pg_catalog.btrim(coalesce(p_role,'')));
  v_pin text := pg_catalog.btrim(coalesce(p_pin,''));
  v_target_id uuid;
  v_idempotency_key text := pg_catalog.btrim(coalesce(p_patch->>'idempotency_key',''));
  v_expected_pin text := nullif(pg_catalog.btrim(coalesce(p_patch->>'expected_current_pin','')), '');
  v_expected_updated_at timestamptz;
  v_request jsonb;
  v_result jsonb;
  v_history jsonb := '{}'::jsonb;
  v_bad_key text;
  v_old_pin text;
  v_effective_name text;
  v_actor_rank integer := 0;
  v_target_rank integer := 0;
  v_requested_rank integer := 0;
begin
  if v_action not in ('CREATE','UPDATE','DEACTIVATE','REACTIVATE') then
    raise exception 'STAFF_ACTION_INVALID:%', v_action;
  end if;
  if v_idempotency_key = '' then raise exception 'STAFF_IDEMPOTENCY_KEY_REQUIRED'; end if;

  select key into v_bad_key
  from pg_catalog.jsonb_object_keys(coalesce(p_patch,'{}'::jsonb)) key
  where key not in (
    'idempotency_key','expected_current_pin','expected_updated_at',
    'salary','avans_manual','borxh_afatgjat','salary_day','bonus_transport','bonus_ushqim',
    'is_hybrid_transport','commission_rate_m2','pay_salary_enabled','pay_meal_enabled',
    'pay_meal_amount','pay_commission_enabled','pay_commission_rate_m2',
    'pay_transport_bonus_enabled','pay_transport_bonus_amount','pay_ready_bonus_enabled',
    'pay_cash_mode','pay_notes'
  ) limit 1;
  if v_bad_key is not null then raise exception 'STAFF_PATCH_KEY_NOT_ALLOWED:%', v_bad_key; end if;

  if nullif(p_patch->>'expected_updated_at','') is not null then
    begin v_expected_updated_at := (p_patch->>'expected_updated_at')::timestamptz;
    exception when others then raise exception 'STAFF_EXPECTED_UPDATED_AT_INVALID'; end;
  end if;

  select * into v_actor
  from public.users u
  where u.pin = pg_catalog.btrim(coalesce(p_actor_pin,'')) and u.is_active is true
  limit 1;
  v_actor_rank := private.staff_role_rank_v1(v_actor.role);
  if not found or v_actor_rank < 20 then raise exception 'STAFF_MANAGER_ONLY'; end if;

  v_target_id := case when v_action='REACTIVATE' then p_reactivate_user_id else p_user_id end;
  if v_action <> 'CREATE' and v_target_id is null then raise exception 'STAFF_EXPLICIT_USER_ID_REQUIRED'; end if;
  if v_action='REACTIVATE' and p_reactivate_user_id is null then raise exception 'STAFF_REACTIVATE_USER_ID_REQUIRED'; end if;

  v_request := pg_catalog.jsonb_build_object(
    'action',v_action,'user_id',p_user_id,'reactivate_user_id',p_reactivate_user_id,
    'name',p_name,'role',p_role,'pin',p_pin,'is_active',p_is_active,
    'patch',coalesce(p_patch,'{}'::jsonb) - 'idempotency_key'
  );
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('staff_identity_idem:' || v_idempotency_key,0)
  );
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('staff_identity_pin_registry_v1',0)
  );
  select * into v_existing from private.staff_identity_merge_log l where l.idempotency_key=v_idempotency_key;
  if found then
    if v_existing.action <> v_action or v_existing.request_payload is distinct from v_request then
      raise exception 'STAFF_IDEMPOTENCY_CONFLICT';
    end if;
    return v_existing.result;
  end if;

  if v_action='CREATE' then
    if v_name='' then raise exception 'STAFF_NAME_REQUIRED'; end if;
    if v_role='' then raise exception 'STAFF_ROLE_REQUIRED'; end if;
    v_requested_rank := private.staff_role_rank_v1(v_role);
    if v_requested_rank<0 then raise exception 'STAFF_ROLE_INVALID'; end if;
    if v_requested_rank>v_actor_rank then raise exception 'STAFF_ROLE_HIERARCHY_DENIED'; end if;
    if v_pin !~ '^[0-9]{3,12}$' then raise exception 'STAFF_PIN_INVALID'; end if;
    if exists (select 1 from private.staff_pin_aliases a where a.alias_pin=v_pin) then
      raise exception 'STAFF_PIN_IS_RETIRED:%',v_pin;
    end if;
    perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(
      'staff_identity_name:' || private.staff_normalize_name_v1(v_name),0
    ));
    if exists (
      select 1 from public.users u
      where private.staff_normalize_name_v1(u.name)=private.staff_normalize_name_v1(v_name)
    ) then raise exception 'STAFF_NAME_MATCH_REQUIRES_REACTIVATION'; end if;

    if p_user_id is null then
      insert into public.users(name,role,pin,is_active)
      values (v_name,v_role,v_pin,coalesce(p_is_active,true))
      returning * into v_after;
    else
      insert into public.users(id,name,role,pin,is_active)
      values (p_user_id,v_name,v_role,v_pin,coalesce(p_is_active,true))
      returning * into v_after;
    end if;
    v_target_id := v_after.id;
  else
    perform pg_catalog.pg_advisory_xact_lock(
      pg_catalog.hashtextextended('staff_identity_user:' || v_target_id::text,0)
    );
    select * into v_before from public.users u where u.id=v_target_id for update;
    if not found then raise exception 'STAFF_USER_NOT_FOUND:%',v_target_id; end if;
    v_target_rank := private.staff_role_rank_v1(v_before.role);
    if v_target_rank>v_actor_rank then raise exception 'STAFF_ROLE_HIERARCHY_DENIED'; end if;
    if v_target_id=v_actor.id and v_action='DEACTIVATE' then
      raise exception 'STAFF_SELF_DEACTIVATE_NOT_ALLOWED';
    end if;
    if v_target_id=v_actor.id and v_role<>''
       and pg_catalog.upper(pg_catalog.btrim(v_role))
           <>pg_catalog.upper(pg_catalog.btrim(coalesce(v_before.role,''))) then
      raise exception 'STAFF_SELF_ROLE_CHANGE_NOT_ALLOWED';
    end if;
    if v_role<>'' then
      v_requested_rank := private.staff_role_rank_v1(v_role);
      if v_requested_rank<0 then raise exception 'STAFF_ROLE_INVALID'; end if;
      if v_requested_rank>v_actor_rank then raise exception 'STAFF_ROLE_HIERARCHY_DENIED'; end if;
    end if;
    if v_expected_pin is not null and v_before.pin is distinct from v_expected_pin then
      raise exception 'STAFF_CURRENT_PIN_STALE expected=% actual=%',v_expected_pin,v_before.pin;
    end if;
    if v_expected_updated_at is not null and v_before.updated_at is distinct from v_expected_updated_at then
      raise exception 'STAFF_UPDATED_AT_STALE expected=% actual=%',v_expected_updated_at,v_before.updated_at;
    end if;
    if v_action='UPDATE' and v_before.is_active is not true then raise exception 'STAFF_USE_REACTIVATE_ACTION'; end if;
    if v_action='REACTIVATE' and v_before.is_active is true then raise exception 'STAFF_USER_ALREADY_ACTIVE'; end if;
    if v_action='UPDATE' and p_is_active is false then raise exception 'STAFF_USE_DEACTIVATE_ACTION'; end if;
    if v_action='DEACTIVATE' and (
      v_name<>'' or v_role<>'' or v_pin<>'' or p_is_active is true
      or (coalesce(p_patch,'{}'::jsonb)
          - 'idempotency_key' - 'expected_current_pin' - 'expected_updated_at') <> '{}'::jsonb
    ) then raise exception 'STAFF_DEACTIVATE_ONLY_ACTION'; end if;

    v_effective_name := case when v_name<>'' then v_name else v_before.name end;
    if v_action in ('UPDATE','REACTIVATE') then
      perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(
        'staff_identity_name:' || private.staff_normalize_name_v1(v_effective_name),0
      ));
    end if;
    if v_action in ('UPDATE','REACTIVATE') and exists (
      select 1 from public.users u
      where u.id<>v_target_id
        and private.staff_normalize_name_v1(u.name)=private.staff_normalize_name_v1(v_effective_name)
    ) then raise exception 'STAFF_NAME_MATCH_REQUIRES_REACTIVATION'; end if;

    v_old_pin := v_before.pin;
    if v_pin<>'' and v_pin<>v_old_pin then
      if v_pin !~ '^[0-9]{3,12}$' then raise exception 'STAFF_PIN_INVALID'; end if;
      if exists (select 1 from public.users u where u.pin=v_pin and u.id<>v_target_id) then
        raise exception 'STAFF_PIN_ALREADY_USED:%',v_pin;
      end if;
      if exists (select 1 from private.staff_pin_aliases a where a.alias_pin=v_pin) then
        raise exception 'STAFF_PIN_IS_RETIRED:%',v_pin;
      end if;
      if exists (
        select 1 from public.offline_code_leases l
        where l.owner_id=v_old_pin and l.status in ('available','assigned')
          and (l.expires_at is null or l.expires_at>pg_catalog.now())
      ) then raise exception 'STAFF_ACTIVE_OFFLINE_LEASE_CONFLICT'; end if;
      if exists (
        select 1 from public.base_code_pool b
        where (b.owner_id=v_old_pin or b.reserved_by=v_old_pin)
          and b.status='reserved'
          and (b.lease_expires_at is null or b.lease_expires_at>pg_catalog.now())
      ) then raise exception 'STAFF_ACTIVE_BASE_RESERVATION_CONFLICT'; end if;

    else
      v_pin := v_old_pin;
    end if;

    update public.users u set
      name=case when v_name<>'' then v_name else u.name end,
      role=case when v_role<>'' then v_role else u.role end,
      pin=v_pin,
      is_active=case when v_action='DEACTIVATE' then false when v_action='REACTIVATE' then true else coalesce(p_is_active,u.is_active) end
    where u.id=v_target_id
    returning * into v_after;

    if v_pin<>v_old_pin then
      v_history := private.canonicalize_staff_history_v1(v_target_id,array[v_old_pin],v_pin,'{}'::uuid[]);
      update private.staff_pin_aliases
      set current_pin_snapshot=v_pin
      where canonical_user_id=v_target_id;
      insert into private.staff_pin_aliases(alias_pin,canonical_user_id,current_pin_snapshot,source_user_id,reason,created_by_pin)
      values(v_old_pin,v_target_id,v_pin,v_target_id,'PIN_ROTATION',v_actor.pin);
    end if;
  end if;

  update public.users u set
    salary=case when p_patch?'salary' then (p_patch->>'salary')::numeric else u.salary end,
    avans_manual=case when p_patch?'avans_manual' then (p_patch->>'avans_manual')::numeric else u.avans_manual end,
    borxh_afatgjat=case when p_patch?'borxh_afatgjat' then (p_patch->>'borxh_afatgjat')::numeric else u.borxh_afatgjat end,
    salary_day=case when p_patch?'salary_day' then nullif(p_patch->>'salary_day','')::integer else u.salary_day end,
    bonus_transport=case when p_patch?'bonus_transport' then (p_patch->>'bonus_transport')::numeric else u.bonus_transport end,
    bonus_ushqim=case when p_patch?'bonus_ushqim' then (p_patch->>'bonus_ushqim')::numeric else u.bonus_ushqim end,
    is_hybrid_transport=case when p_patch?'is_hybrid_transport' then (p_patch->>'is_hybrid_transport')::boolean else u.is_hybrid_transport end,
    commission_rate_m2=case when p_patch?'commission_rate_m2' then (p_patch->>'commission_rate_m2')::numeric else u.commission_rate_m2 end,
    pay_salary_enabled=case when p_patch?'pay_salary_enabled' then (p_patch->>'pay_salary_enabled')::boolean else u.pay_salary_enabled end,
    pay_meal_enabled=case when p_patch?'pay_meal_enabled' then (p_patch->>'pay_meal_enabled')::boolean else u.pay_meal_enabled end,
    pay_meal_amount=case when p_patch?'pay_meal_amount' then (p_patch->>'pay_meal_amount')::numeric else u.pay_meal_amount end,
    pay_commission_enabled=case when p_patch?'pay_commission_enabled' then (p_patch->>'pay_commission_enabled')::boolean else u.pay_commission_enabled end,
    pay_commission_rate_m2=case when p_patch?'pay_commission_rate_m2' then (p_patch->>'pay_commission_rate_m2')::numeric else u.pay_commission_rate_m2 end,
    pay_transport_bonus_enabled=case when p_patch?'pay_transport_bonus_enabled' then (p_patch->>'pay_transport_bonus_enabled')::boolean else u.pay_transport_bonus_enabled end,
    pay_transport_bonus_amount=case when p_patch?'pay_transport_bonus_amount' then (p_patch->>'pay_transport_bonus_amount')::numeric else u.pay_transport_bonus_amount end,
    pay_ready_bonus_enabled=case when p_patch?'pay_ready_bonus_enabled' then (p_patch->>'pay_ready_bonus_enabled')::boolean else u.pay_ready_bonus_enabled end,
    pay_cash_mode=case when p_patch?'pay_cash_mode' then p_patch->>'pay_cash_mode' else u.pay_cash_mode end,
    pay_notes=case when p_patch?'pay_notes' then p_patch->>'pay_notes' else u.pay_notes end,
    pay_updated_at=case when p_patch-'idempotency_key'-'expected_current_pin'-'expected_updated_at'<>'{}'::jsonb then pg_catalog.now() else u.pay_updated_at end,
    pay_updated_by_pin=case when p_patch-'idempotency_key'-'expected_current_pin'-'expected_updated_at'<>'{}'::jsonb then v_actor.pin else u.pay_updated_by_pin end,
    pay_updated_by_name=case when p_patch-'idempotency_key'-'expected_current_pin'-'expected_updated_at'<>'{}'::jsonb then v_actor.name else u.pay_updated_by_name end
  where u.id=v_target_id
  returning * into v_after;

  v_result := pg_catalog.jsonb_build_object(
    'ok',true,'action',v_action,'user',pg_catalog.to_jsonb(v_after),
    'history',v_history,'idempotency_key',v_idempotency_key
  );
  insert into private.staff_identity_merge_log(
    idempotency_key,action,canonical_user_id,source_user_id,old_pins,new_pin,
    actor_pin,request_payload,before_snapshot,after_snapshot,result
  ) values (
    v_idempotency_key,v_action,v_target_id,null,
    case when v_old_pin is null or v_old_pin=v_after.pin then '{}'::text[] else array[v_old_pin] end,
    v_after.pin,v_actor.pin,v_request,
    case when v_before.id is null then '{}'::jsonb else pg_catalog.to_jsonb(v_before) end,
    pg_catalog.to_jsonb(v_after),v_result
  );
  return v_result;
end;
$$;

