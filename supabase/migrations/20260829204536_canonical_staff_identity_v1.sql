  reason text not null,
  created_by_pin text not null,
  created_at timestamptz not null default pg_catalog.now(),
  constraint staff_pin_alias_digits_chk check (alias_pin ~ '^[0-9]{3,12}$'),
  constraint staff_pin_alias_not_current_chk check (alias_pin <> current_pin_snapshot)
);

create index if not exists staff_pin_aliases_user_idx
  on private.staff_pin_aliases(canonical_user_id, retired_at desc);

