create or replace function private.guard_staff_pin_alias_v1()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('staff_identity_pin_registry_v1',0)
  );
  new.alias_pin := pg_catalog.btrim(coalesce(new.alias_pin, ''));
  new.current_pin_snapshot := pg_catalog.btrim(coalesce(new.current_pin_snapshot, ''));

  if exists (
    select 1 from public.users u where pg_catalog.btrim(u.pin) = new.alias_pin
  ) then
    raise exception 'STAFF_ALIAS_COLLIDES_WITH_CURRENT_PIN:%', new.alias_pin;
  end if;

  if not exists (
    select 1 from public.users u where u.id = new.canonical_user_id
  ) then
    raise exception 'STAFF_ALIAS_CANONICAL_USER_NOT_FOUND:%', new.canonical_user_id;
  end if;

  return new;
end;
$$;

