create or replace function public.merge_staff_identity_v1(
  p_actor_pin text,
  p_canonical_user_id uuid,
  p_source_user_id uuid,
  p_expected_canonical_pin text,
  p_expected_source_pin text,
  p_retired_pins text[],
  p_idempotency_key text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor public.users%rowtype;
  v_canonical public.users%rowtype;
  v_source public.users%rowtype;
  v_existing private.staff_identity_merge_log%rowtype;
  v_old_pins text[];
  v_request jsonb;
  v_before_checksum jsonb;
  v_after_checksum jsonb;
  v_history jsonb;
  v_before jsonb;
  v_after jsonb;
  v_result jsonb;
  v_alias text;
  v_source_ids uuid[] := '{}'::uuid[];
  v_source_id_texts text[] := '{}'::text[];
  v_actor_rank integer := 0;
begin
  if pg_catalog.btrim(coalesce(p_idempotency_key,'')) = '' then
    raise exception 'STAFF_IDEMPOTENCY_KEY_REQUIRED';
  end if;
  if p_canonical_user_id is null then raise exception 'STAFF_CANONICAL_USER_ID_REQUIRED'; end if;

  select coalesce(pg_catalog.array_agg(distinct pin order by pin), '{}'::text[])
  into v_old_pins
  from (
    select pg_catalog.btrim(x) pin
    from pg_catalog.unnest(coalesce(p_retired_pins, '{}'::text[])) x
    where pg_catalog.btrim(coalesce(x,'')) <> ''
    union
    select pg_catalog.btrim(p_expected_source_pin)
    where pg_catalog.btrim(coalesce(p_expected_source_pin,'')) <> ''
  ) q;

  v_request := pg_catalog.jsonb_build_object(
    'canonical_user_id', p_canonical_user_id,
    'source_user_id', p_source_user_id,
    'expected_canonical_pin', pg_catalog.btrim(coalesce(p_expected_canonical_pin,'')),
    'expected_source_pin', pg_catalog.btrim(coalesce(p_expected_source_pin,'')),
    'retired_pins', v_old_pins
  );

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('staff_identity_idem:' || p_idempotency_key, 0)
  );
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('staff_identity_pin_registry_v1',0)
  );

  select * into v_existing
  from private.staff_identity_merge_log l
  where l.idempotency_key = p_idempotency_key;
  if found then
    if v_existing.action not in ('CANONICALIZE','MERGE')
       or v_existing.request_payload is distinct from v_request then
      raise exception 'STAFF_IDEMPOTENCY_CONFLICT';
    end if;
    return v_existing.result;
  end if;

  select * into v_actor
  from public.users u
  where u.pin = pg_catalog.btrim(coalesce(p_actor_pin,''))
    and u.is_active is true
  limit 1;
  v_actor_rank := private.staff_role_rank_v1(v_actor.role);
  if not found or v_actor_rank < 20 then
    raise exception 'STAFF_MANAGER_ONLY';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('staff_identity_user:' || p_canonical_user_id::text, 0)
  );
  if p_source_user_id is not null then
    perform pg_catalog.pg_advisory_xact_lock(
      pg_catalog.hashtextextended('staff_identity_user:' || p_source_user_id::text, 0)
    );
  end if;

  select * into v_canonical
  from public.users u where u.id = p_canonical_user_id for update;
  if not found then raise exception 'STAFF_CANONICAL_USER_NOT_FOUND'; end if;
  if v_canonical.pin is distinct from pg_catalog.btrim(p_expected_canonical_pin) then
    raise exception 'STAFF_CANONICAL_PIN_STALE expected=% actual=%', p_expected_canonical_pin, v_canonical.pin;
  end if;
  if v_canonical.is_active is not true then raise exception 'STAFF_CANONICAL_USER_NOT_ACTIVE'; end if;
  if private.staff_role_rank_v1(v_canonical.role) > v_actor_rank then
    raise exception 'STAFF_ROLE_HIERARCHY_DENIED';
  end if;

  foreach v_alias in array v_old_pins loop
    if v_alias !~ '^[0-9]{3,12}$' then raise exception 'STAFF_RETIRED_PIN_INVALID:%', v_alias; end if;
    if v_alias = v_canonical.pin then raise exception 'STAFF_ALIAS_EQUALS_CURRENT_PIN:%', v_alias; end if;
    if exists (select 1 from public.users u where u.pin = v_alias and u.id <> coalesce(p_source_user_id, p_canonical_user_id)) then
      raise exception 'STAFF_ALIAS_OWNED_BY_OTHER_USER:%', v_alias;
    end if;
    if exists (
      select 1 from private.staff_pin_aliases a
      where a.alias_pin = v_alias
        and a.canonical_user_id<>p_canonical_user_id
        and (p_source_user_id is null or a.canonical_user_id<>p_source_user_id)
    ) then
      raise exception 'STAFF_ALIAS_OWNED_BY_OTHER_IDENTITY:%', v_alias;
    end if;
  end loop;

  if p_source_user_id is not null then
    if p_source_user_id = p_canonical_user_id then raise exception 'STAFF_SOURCE_EQUALS_CANONICAL'; end if;
    select * into v_source from public.users u where u.id = p_source_user_id for update;
    if not found then raise exception 'STAFF_SOURCE_USER_NOT_FOUND'; end if;
    if v_source.pin is distinct from pg_catalog.btrim(p_expected_source_pin) then
      raise exception 'STAFF_SOURCE_PIN_STALE expected=% actual=%', p_expected_source_pin, v_source.pin;
    end if;
    if v_source.is_active is true then raise exception 'STAFF_SOURCE_MUST_BE_INACTIVE'; end if;
    if private.staff_normalize_name_v1(v_source.name) <> private.staff_normalize_name_v1(v_canonical.name)
       or pg_catalog.upper(pg_catalog.btrim(coalesce(v_source.role,'')))
          <> pg_catalog.upper(pg_catalog.btrim(coalesce(v_canonical.role,''))) then
      raise exception 'STAFF_SOURCE_IDENTITY_MISMATCH';
    end if;
    v_source_ids := array[p_source_user_id];
    v_source_id_texts := array[p_source_user_id::text];

    select coalesce(pg_catalog.array_agg(distinct x order by x),'{}'::text[])
    into v_old_pins
    from (
      select p pin from pg_catalog.unnest(v_old_pins) p
      union
      select a.alias_pin from private.staff_pin_aliases a
      where a.canonical_user_id=p_source_user_id
    ) aliases(x);

    foreach v_alias in array v_old_pins loop
      if v_alias=v_canonical.pin then raise exception 'STAFF_ALIAS_EQUALS_CURRENT_PIN:%',v_alias; end if;
      if exists(
        select 1 from public.users u
        where u.pin=v_alias and u.id not in (p_canonical_user_id,p_source_user_id)
      ) then raise exception 'STAFF_ALIAS_OWNED_BY_OTHER_USER:%',v_alias; end if;
      if exists(
        select 1 from private.staff_pin_aliases a
        where a.alias_pin=v_alias
          and a.canonical_user_id not in (p_canonical_user_id,p_source_user_id)
      ) then raise exception 'STAFF_ALIAS_OWNED_BY_OTHER_IDENTITY:%',v_alias; end if;
    end loop;
  end if;

  -- Active/indeterminate allocator ownership must be explicitly resolved before
  -- a PIN move. Expired, unreferenced BASE reservations are safely released by
  -- canonicalize_staff_history_v1; terminal USED ownership is canonicalized.
  if exists (
    select 1 from public.offline_code_leases l
    where l.owner_id = any(v_old_pins || v_source_id_texts)
      and l.status in ('available','assigned')
      and (l.expires_at is null or l.expires_at > pg_catalog.now())
  ) then raise exception 'STAFF_ACTIVE_OFFLINE_LEASE_CONFLICT'; end if;
  if exists (
    select 1 from public.base_code_pool b
    where (b.owner_id = any(v_old_pins) or b.reserved_by = any(v_old_pins))
      and b.status = 'reserved'
      and (b.lease_expires_at is null or b.lease_expires_at > pg_catalog.now())
  ) then raise exception 'STAFF_ACTIVE_BASE_RESERVATION_CONFLICT'; end if;

  if exists (
    select 1
    from public.payroll_month_close_items old_i
    join public.payroll_month_close_items new_i
      on new_i.close_id = old_i.close_id
     and new_i.worker_pin = v_canonical.pin
     and new_i.id <> old_i.id
    where old_i.worker_pin = any(v_old_pins)
  ) then raise exception 'STAFF_PAYROLL_PIN_CONFLICT'; end if;

  -- tepiha_device_approvals is a security mirror. The history helper re-keys it
  -- only after synchronizing approved=false/true from the authoritative UUID-
  -- linked tepiha_user_devices row; unmatched mirrors become false.

  if p_source_user_id is not null and exists (
    select 1
    from public.worker_employment_terms s
    join public.worker_employment_terms c
      on c.user_id = p_canonical_user_id and c.effective_from = s.effective_from
    where s.user_id = p_source_user_id
      and (pg_catalog.to_jsonb(s) - array['id','user_id','created_at']::text[])
          is distinct from (pg_catalog.to_jsonb(c) - array['id','user_id','created_at']::text[])
  ) then raise exception 'STAFF_EMPLOYMENT_TERMS_CONFLICT'; end if;

  v_before_checksum := private.staff_financial_checksum_v1(v_old_pins || array[v_canonical.pin]);
  v_before := pg_catalog.jsonb_build_object(
    'canonical_user', pg_catalog.to_jsonb(v_canonical),
    'source_user', case when p_source_user_id is null then null else pg_catalog.to_jsonb(v_source) end,
    'user_devices',(
      select coalesce(pg_catalog.jsonb_agg(pg_catalog.to_jsonb(d) order by d.id),'[]'::jsonb)
      from public.tepiha_user_devices d
      where d.user_id=p_canonical_user_id or d.user_id=p_source_user_id
    ),
    'device_approvals',(
      select coalesce(pg_catalog.jsonb_agg(pg_catalog.to_jsonb(a) order by a.id),'[]'::jsonb)
      from public.tepiha_device_approvals a
      where a.pin=any(v_old_pins || array[v_canonical.pin])
    ),
    'employment_terms',(
      select coalesce(pg_catalog.jsonb_agg(pg_catalog.to_jsonb(t) order by t.effective_from),'[]'::jsonb)
      from public.worker_employment_terms t
      where t.user_id=p_canonical_user_id or t.user_id=p_source_user_id
    ),
    'financial_checksum', v_before_checksum
  );

  if p_source_user_id is not null then
    if exists (
      select 1
      from public.tepiha_user_devices s
      join public.tepiha_user_devices c
        on c.user_id = p_canonical_user_id
       and c.device_id = s.device_id
      where s.user_id = p_source_user_id
    ) then raise exception 'STAFF_DEVICE_LINK_CONFLICT'; end if;

    delete from public.worker_employment_terms s
    using public.worker_employment_terms c
    where s.user_id = p_source_user_id
      and c.user_id = p_canonical_user_id
      and c.effective_from = s.effective_from
      and (pg_catalog.to_jsonb(s) - array['id','user_id','created_at']::text[])
          is not distinct from (pg_catalog.to_jsonb(c) - array['id','user_id','created_at']::text[]);

    update public.worker_employment_terms set user_id = p_canonical_user_id
    where user_id = p_source_user_id;

    -- Preserve each device row's actual is_approved flag. Only identity linkage changes.
    update public.tepiha_user_devices
    set user_id = p_canonical_user_id, requested_pin = v_canonical.pin
    where user_id = p_source_user_id;

    update private.staff_pin_aliases
    set canonical_user_id=p_canonical_user_id,
        current_pin_snapshot=v_canonical.pin
    where canonical_user_id=p_source_user_id;
  end if;

  v_history := private.canonicalize_staff_history_v1(
    p_canonical_user_id, v_old_pins, v_canonical.pin, v_source_ids
  );

  if p_source_user_id is not null then
    delete from public.users where id = p_source_user_id;
    if not found then raise exception 'STAFF_SOURCE_DELETE_FAILED'; end if;
  end if;

  foreach v_alias in array v_old_pins loop
    insert into private.staff_pin_aliases(
      alias_pin, canonical_user_id, current_pin_snapshot, source_user_id,
      reason, created_by_pin
    ) values (
      v_alias, p_canonical_user_id, v_canonical.pin, p_source_user_id,
      case when p_source_user_id is null then 'PIN_ROTATION_HISTORY' else 'DUPLICATE_USER_MERGE' end,
      v_actor.pin
    )
    on conflict (alias_pin) do update
      set current_pin_snapshot = excluded.current_pin_snapshot,
          retired_at = coalesce(private.staff_pin_aliases.retired_at, pg_catalog.now()),
          reason = excluded.reason,
          created_by_pin = excluded.created_by_pin
      where private.staff_pin_aliases.canonical_user_id = excluded.canonical_user_id;
  end loop;

  v_after_checksum := private.staff_financial_checksum_v1(array[v_canonical.pin]);
  if v_after_checksum is distinct from v_before_checksum then
    raise exception 'STAFF_FINANCIAL_CHECKSUM_MISMATCH before=% after=%', v_before_checksum, v_after_checksum;
  end if;

  select * into v_canonical from public.users u where u.id = p_canonical_user_id;
  v_after := pg_catalog.jsonb_build_object(
    'canonical_user', pg_catalog.to_jsonb(v_canonical),
    'source_deleted', p_source_user_id is null or not exists(select 1 from public.users u where u.id=p_source_user_id),
    'user_devices',(
      select coalesce(pg_catalog.jsonb_agg(pg_catalog.to_jsonb(d) order by d.id),'[]'::jsonb)
      from public.tepiha_user_devices d where d.user_id=p_canonical_user_id
    ),
    'device_approvals',(
      select coalesce(pg_catalog.jsonb_agg(pg_catalog.to_jsonb(a) order by a.id),'[]'::jsonb)
      from public.tepiha_device_approvals a where a.pin=v_canonical.pin
    ),
    'employment_terms',(
      select coalesce(pg_catalog.jsonb_agg(pg_catalog.to_jsonb(t) order by t.effective_from),'[]'::jsonb)
      from public.worker_employment_terms t where t.user_id=p_canonical_user_id
    ),
    'financial_checksum', v_after_checksum,
    'history', v_history
  );
  v_result := pg_catalog.jsonb_build_object(
    'ok', true, 'action', case when p_source_user_id is null then 'CANONICALIZE' else 'MERGE' end,
    'canonical_user_id', p_canonical_user_id, 'pin', v_canonical.pin,
    'retired_pins', v_old_pins, 'source_user_id', p_source_user_id,
    'history', v_history, 'idempotency_key', p_idempotency_key
  );

  insert into private.staff_identity_merge_log(
    idempotency_key, action, canonical_user_id, source_user_id, old_pins,
    new_pin, actor_pin, request_payload, before_snapshot, after_snapshot, result
  ) values (
    p_idempotency_key,
    case when p_source_user_id is null then 'CANONICALIZE' else 'MERGE' end,
    p_canonical_user_id, p_source_user_id, v_old_pins, v_canonical.pin,
    v_actor.pin, v_request, v_before, v_after, v_result
  );

  return v_result;
end;
$$;

