-- Private helpers are not exposed to client roles.
create or replace function private.assert_handoff_receipt_chain_v1(
  p_handoff_id bigint,p_worker_id uuid,p_expected numeric,p_received numeric,p_resolved numeric,p_outstanding numeric,p_ledger_id bigint
) returns void language plpgsql set search_path=pg_catalog,public,private as $fn$
declare v_cash numeric; v_resolved numeric; v_count integer; v_bad integer;
begin
  select count(*)::int,coalesce(sum(amount) filter(where event_kind='RECEIPT'),0),coalesce(sum(amount) filter(where event_kind='RESOLUTION'),0)
  into v_count,v_cash,v_resolved from public.cash_handoff_receipt_events where handoff_id=p_handoff_id;
  if v_count=0 or v_cash<>p_received or v_resolved<>p_resolved or p_expected<>p_received+p_resolved+p_outstanding or p_outstanding<0 then
    raise exception 'HANDOFF_RECEIPT_CHAIN_TOTALS_INVALID';
  end if;
  select count(*) into v_bad from public.cash_handoff_receipt_events e
  left join public.company_budget_ledger l on l.id=e.ledger_entry_id
  where e.handoff_id=p_handoff_id and (
    e.worker_id<>p_worker_id
    or (e.event_kind='RECEIPT' and e.amount>0 and (l.id is null or l.source_type<>'cash_handoff_receipt' or l.source_id<>e.id or l.related_handoff_id is distinct from p_handoff_id or l.direction<>'IN' or l.amount<>e.amount))
    or ((e.event_kind='RESOLUTION' or e.amount=0) and e.ledger_entry_id is not null)
  );
  if v_bad>0 or (p_received>0 and not exists(select 1 from public.cash_handoff_receipt_events where handoff_id=p_handoff_id and ledger_entry_id=p_ledger_id and event_kind='RECEIPT' and amount>0))
     or (p_received=0 and p_ledger_id is not null) then raise exception 'HANDOFF_RECEIPT_CHAIN_LEDGER_INVALID'; end if;
end;
$fn$;
revoke all on function private.assert_handoff_receipt_chain_v1(bigint,uuid,numeric,numeric,numeric,numeric,bigint) from public,anon,authenticated;

create or replace function private.guard_handoff_receipt_event_v1() returns trigger language plpgsql set search_path=pg_catalog,public,private as $fn$
begin
  if tg_op='DELETE' then raise exception 'HANDOFF_RECEIPT_EVENT_IMMUTABLE'; end if;
  if current_user<>'postgres' or current_setting('tepiha.handoff_receipt_context',true) is distinct from 'on' then raise exception 'HANDOFF_RECEIPT_SERVER_ONLY'; end if;
  if tg_op='UPDATE' and (old.ledger_entry_id is not null or new.ledger_entry_id is null or (to_jsonb(new)-'ledger_entry_id') is distinct from (to_jsonb(old)-'ledger_entry_id')) then raise exception 'HANDOFF_RECEIPT_EVENT_IMMUTABLE'; end if;
  return new;
end;
$fn$;
