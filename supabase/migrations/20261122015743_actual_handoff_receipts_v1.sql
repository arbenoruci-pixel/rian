create or replace function private.assert_handoff_receipt_event_v1() returns trigger language plpgsql security definer set search_path=pg_catalog,public,private as $fn$
declare h public.cash_handoffs%rowtype;
begin
  select * into h from public.cash_handoffs where id=new.handoff_id;
  if h.receipt_tracking is not true then raise exception 'HANDOFF_RECEIPT_EVENT_WITHOUT_HANDOFF'; end if;
  perform private.assert_handoff_receipt_chain_v1(h.id,h.receipt_worker_id,h.amount,h.receipt_received_amount,h.receipt_resolved_amount,h.receipt_outstanding_amount,h.company_ledger_entry_id);
  return new;
end;
