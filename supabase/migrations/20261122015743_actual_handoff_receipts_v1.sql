create or replace function private.close_arka_day_receipts_v1(p_actor_id uuid,p_date date,p_counted_cash numeric,p_expected_budget numeric,p_reason text,p_note text,p_request_key text,p_dry_run boolean)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public,private as $fn$
declare a public.users%rowtype; v_balance numeric; v_result jsonb; v_hash text; v_previous_context text; v_existing public.cash_handoff_close_requests%rowtype;
begin
  select * into a from public.users where id=p_actor_id and is_active is true;
  if not found or upper(coalesce(a.role,'')) not in ('DISPATCH','MASTER','MASTER USER','MASTER_USER','MASTERUSER','ADMIN','ADMIN_MASTER','OWNER','PRONAR','SUPERADMIN') then raise exception 'HANDOFF_RECEIPT_FORBIDDEN'; end if;
  if p_expected_budget is null or p_expected_budget::text in ('NaN','Infinity','-Infinity') or p_expected_budget<>round(p_expected_budget,2)
     or p_counted_cash is null or p_counted_cash::text in ('NaN','Infinity','-Infinity') or p_counted_cash<0 or p_counted_cash<>round(p_counted_cash,2) then raise exception 'HANDOFF_RECEIPT_AMOUNT_INVALID'; end if;
  if p_request_key is null or p_request_key!~'^[A-Za-z0-9:_-]{12,120}$' then raise exception 'HANDOFF_RECEIPT_KEY_INVALID'; end if;
  v_hash:=md5(jsonb_build_array(p_date,p_counted_cash,p_expected_budget,trim(coalesce(p_reason,'')),trim(coalesce(p_note,'')))::text);
  perform pg_advisory_xact_lock(hashtext('HANDOFF_CLOSE_REQUEST:'||a.id::text||':'||p_request_key));
  if not p_dry_run then
    select * into v_existing from public.cash_handoff_close_requests where actor_id=a.id and request_key=p_request_key;
    if found then
      if v_existing.payload_hash<>v_hash then raise exception 'HANDOFF_RECEIPT_IDEMPOTENCY_CONFLICT'; end if;
      return v_existing.result||jsonb_build_object('replayed',true);
    end if;
    if not exists(select 1 from public.cash_handoff_receipt_settings where id=1 and enabled) then raise exception 'HANDOFF_RECEIPT_WORKFLOW_PAUSED'; end if;
  end if;
  -- Match the legacy close lock order before taking the shared budget lock.
  perform pg_advisory_xact_lock(hashtext('ARKA_DAILY_CLOSE_V2:'||coalesce(p_date,(now() at time zone 'Europe/Belgrade'-interval '4 hours')::date)::text));
  -- Lock the physical budget before the comparison and retain the lock through
  -- close_arka_day_v2 so a concurrent receipt cannot become a false shortage.
  select current_balance into v_balance from public.company_budget_summary where id=1 for update;
  if v_balance is distinct from p_expected_budget then raise exception 'HANDOFF_RECEIPT_BUDGET_CHANGED'; end if;
  v_result:=public.close_arka_day_v2(a.pin,a.name,p_date,'{}'::bigint[],p_counted_cash,p_reason,p_note,p_request_key,p_dry_run);
  if not p_dry_run then
    v_previous_context:=current_setting('tepiha.handoff_receipt_close_context',true);
    perform set_config('tepiha.handoff_receipt_close_context','on',true);
    insert into public.cash_handoff_close_requests(actor_id,request_key,payload_hash,result)values(a.id,p_request_key,v_hash,v_result);
    perform set_config('tepiha.handoff_receipt_close_context',coalesce(v_previous_context,''),true);
  end if;
  return v_result;
end;
