-- A stable read uses one database snapshot for cards and totals, so a receipt
-- arriving between HTTP queries cannot make the page contradict itself.
create or replace function private.read_cash_handoff_receipts_v1(p_actor_id uuid,p_worker_pin text default null)
returns jsonb language plpgsql stable security definer set search_path=pg_catalog,public,private as $fn$
declare
  a public.users%rowtype; v_manager boolean; v_pin text:=nullif(trim(p_worker_pin),'');
  v_date date:=(now() at time zone 'Europe/Belgrade')::date; v_start timestamptz; v_end timestamptz;
  v_handoffs jsonb; v_events jsonb; v_outstanding numeric; v_received numeric;
begin
  select * into a from public.users where id=p_actor_id and is_active is true;
  if not found then raise exception 'HANDOFF_RECEIPT_FORBIDDEN'; end if;
  v_manager:=upper(coalesce(a.role,'')) in ('DISPATCH','MASTER','MASTER USER','MASTER_USER','MASTERUSER','ADMIN','ADMIN_MASTER','OWNER','PRONAR','SUPERADMIN');
  if not v_manager and v_pin is not null and v_pin<>a.pin then raise exception 'HANDOFF_RECEIPT_FORBIDDEN'; end if;
  if not v_manager then v_pin:=a.pin; end if;
  v_start:=v_date::timestamp at time zone 'Europe/Belgrade';
  v_end:=(v_date+1)::timestamp at time zone 'Europe/Belgrade';
  if (select count(*) from public.cash_handoffs where status='PENDING_DISPATCH_APPROVAL' and (v_pin is null or worker_pin=v_pin))>5000 then raise exception 'HANDOFF_RECEIPT_REPORT_TOO_LARGE'; end if;
  with selected as (
    select h.* from public.cash_handoffs h where h.status='PENDING_DISPATCH_APPROVAL' and (v_pin is null or h.worker_pin=v_pin)
    union all
    (select h.* from public.cash_handoffs h where h.receipt_tracking and h.status='ACCEPTED' and (v_pin is null or h.worker_pin=v_pin) order by h.receipt_updated_at desc,h.id desc limit 40)
  )
  select coalesce(jsonb_agg(to_jsonb(h)||jsonb_build_object(
    'worker_id',coalesce(h.receipt_worker_id,u.id),'pay_ready_bonus_enabled',coalesce(u.pay_ready_bonus_enabled,false),'can_receive',v_manager and coalesce(h.receipt_worker_id,u.id)<>a.id,
    'has_bonus_allocations',exists(select 1 from public.base_ready_bonus_allocations where handoff_id=h.id),
    'pending_payment_ids',coalesce((select jsonb_agg(i.pending_payment_id order by i.id) from public.cash_handoff_items i where i.handoff_id=h.id and i.released_at is null),'[]'::jsonb)
  ) order by h.submitted_at,h.id),'[]'::jsonb)
  into v_handoffs from selected h left join public.users u on u.pin=h.worker_pin;
  select coalesce(jsonb_agg(to_jsonb(e) order by e.id),'[]'::jsonb) into v_events
  from public.cash_handoff_receipt_events e where e.handoff_id in (select (value->>'id')::bigint from jsonb_array_elements(v_handoffs));
  select coalesce(sum(case when receipt_tracking then receipt_outstanding_amount else amount end),0) into v_outstanding
  from public.cash_handoffs where status='PENDING_DISPATCH_APPROVAL' and (v_pin is null or worker_pin=v_pin);
  select coalesce(sum(amount),0) into v_received from (
    select amount from public.cash_handoffs where status='ACCEPTED' and not receipt_tracking and decided_at>=v_start and decided_at<v_end and (v_pin is null or worker_pin=v_pin)
    union all
    select e.amount from public.cash_handoff_receipt_events e join public.cash_handoffs h on h.id=e.handoff_id where e.event_kind='RECEIPT' and e.created_at>=v_start and e.created_at<v_end and (v_pin is null or h.worker_pin=v_pin)
  ) r;
  return jsonb_build_object('ok',true,'manager',v_manager,'actorId',a.id,'handoffs',v_handoffs,'events',v_events,
    'summary',jsonb_build_object('outstandingTotal',v_outstanding,'receivedToday',v_received,'date',v_date,'timeZone','Europe/Belgrade'),'generated_at',now());
end;
