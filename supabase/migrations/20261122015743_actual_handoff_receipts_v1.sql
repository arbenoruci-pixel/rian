create or replace function private.guard_receipted_handoff_item_v1() returns trigger language plpgsql set search_path=pg_catalog,public,private as $fn$
begin
  -- Serialize even a cached direct item edit with the first receipt. Recheck
  -- after the handoff lock, so an edit that began before it became tracked
  -- cannot commit a released/moved item after the cash receipt commits.
  perform 1 from public.cash_handoffs where id in (
    case when tg_op='INSERT' then new.handoff_id else old.handoff_id end,
    case when tg_op='UPDATE' then new.handoff_id else null end
  ) order by id for update;
  if exists(select 1 from public.cash_handoffs where receipt_tracking and id=case when tg_op='INSERT' then new.handoff_id else old.handoff_id end)
     or (tg_op='UPDATE' and exists(select 1 from public.cash_handoffs where receipt_tracking and id=new.handoff_id)) then
    raise exception 'RECEIPTED_HANDOFF_ITEMS_ARE_IMMUTABLE';
  end if;
  return case when tg_op='DELETE' then old else new end;
end;
$fn$;
revoke all on function private.guard_receipted_handoff_item_v1() from public,anon,authenticated;
drop trigger if exists trg_00_guard_receipted_handoff_item_v1 on public.cash_handoff_items;
create trigger trg_00_guard_receipted_handoff_item_v1 before insert or update or delete on public.cash_handoff_items for each row execute function private.guard_receipted_handoff_item_v1();

-- Add tightly scoped receipt branches to the existing guards. Their legacy
-- bodies remain byte-for-byte intact after the insertion point.
do $patch$
declare v_name text; v_def text; v_branch text; v_at integer;
begin
  for v_name,v_branch in select * from (values
    ('guard_cash_handoff_v1',$branch$
  -- HANDOFF_RECEIPTS_V1
  if (tg_op='UPDATE' and (old.receipt_tracking or new.receipt_tracking)) or (tg_op='INSERT' and new.receipt_tracking) then
    if tg_op<>'UPDATE' or not new.receipt_tracking or current_user<>'postgres' or current_setting('tepiha.handoff_receipt_context',true) is distinct from 'on' then raise exception 'HANDOFF_RECEIPT_USE_ACTUAL_RECEIPT'; end if;
    if new.amount is distinct from old.amount or new.worker_pin is distinct from old.worker_pin or new.worker_name is distinct from old.worker_name
       or (old.receipt_tracking and new.receipt_worker_id is distinct from old.receipt_worker_id)
       or old.status<>'PENDING_DISPATCH_APPROVAL' or new.status not in ('PENDING_DISPATCH_APPROVAL','ACCEPTED') then raise exception 'HANDOFF_RECEIPT_EXPECTATION_IMMUTABLE'; end if;
    if not exists(select 1 from public.users where id=new.receipt_worker_id and pin=new.worker_pin) then raise exception 'HANDOFF_RECEIPT_WORKER_MISMATCH'; end if;
    if (new.status='ACCEPTED') is distinct from (new.receipt_outstanding_amount=0) then raise exception 'HANDOFF_RECEIPT_STATUS_INVALID'; end if;
    perform private.assert_handoff_receipt_chain_v1(new.id,new.receipt_worker_id,new.amount,new.receipt_received_amount,new.receipt_resolved_amount,new.receipt_outstanding_amount,new.company_ledger_entry_id);
    if exists(select 1 from public.company_budget_ledger where source_type='cash_handoff' and source_id=new.id) then raise exception 'HANDOFF_RECEIPT_LEGACY_LEDGER_EXISTS'; end if;
    if (select coalesce(sum(amount),0) from public.cash_handoff_items where handoff_id=new.id and released_at is null)<>new.amount
       or exists(select 1 from public.cash_handoff_items i left join public.arka_pending_payments p on p.id=i.pending_payment_id where i.handoff_id=new.id and (i.released_at is not null or p.id is null or p.status<>'PENDING_DISPATCH_APPROVAL')) then raise exception 'HANDOFF_RECEIPT_ITEMS_CHANGED'; end if;
    return new;
  end if;
$branch$),
    ('guard_company_budget_ledger_v1',$branch$
  -- HANDOFF_RECEIPTS_V1
  if tg_op='INSERT' and lower(coalesce(new.source_type,''))='cash_handoff' and exists(select 1 from public.cash_handoffs where id=new.source_id and receipt_tracking) then raise exception 'HANDOFF_RECEIPT_USE_ACTUAL_RECEIPT'; end if;
  if (tg_op='INSERT' and new.source_type='cash_handoff_receipt') or (tg_op='UPDATE' and (old.source_type='cash_handoff_receipt' or new.source_type='cash_handoff_receipt')) then
    if tg_op<>'INSERT' or current_user<>'postgres' or current_setting('tepiha.handoff_receipt_context',true) is distinct from 'on' then raise exception 'HANDOFF_RECEIPT_LEDGER_IMMUTABLE'; end if;
    if not exists(select 1 from public.cash_handoff_receipt_events e join public.cash_handoffs h on h.id=e.handoff_id where e.id=new.source_id and e.event_kind='RECEIPT' and e.amount>0 and e.amount=new.amount and new.direction='IN' and new.related_handoff_id=h.id and e.ledger_entry_id is null and h.status='PENDING_DISPATCH_APPROVAL') then raise exception 'HANDOFF_RECEIPT_LEDGER_INVALID'; end if;
    return new;
  end if;
$branch$),
    ('guard_arka_cash_payment_v1',$branch$
  -- HANDOFF_RECEIPTS_V1
  if tg_op='UPDATE' and new.status is distinct from old.status and exists(select 1 from public.cash_handoff_items i join public.cash_handoffs h on h.id=i.handoff_id where i.pending_payment_id=old.id and h.receipt_tracking) then
    if old.status<>'PENDING_DISPATCH_APPROVAL' or new.status<>'ACCEPTED_BY_DISPATCH' or current_user<>'postgres' or current_setting('tepiha.handoff_receipt_context',true) is distinct from 'on'
       or (select count(*) from public.cash_handoff_items i join public.cash_handoffs h on h.id=i.handoff_id where i.pending_payment_id=old.id and i.released_at is null and h.receipt_tracking and h.status='ACCEPTED' and h.receipt_outstanding_amount=0)<>1
       or (to_jsonb(new)-array['status','approved_by_pin','approved_by_name','handed_at','handed_by_pin','handed_by_name','handed_by_role','updated_at']::text[]) is distinct from (to_jsonb(old)-array['status','approved_by_pin','approved_by_name','handed_at','handed_by_pin','handed_by_name','handed_by_role','updated_at']::text[]) then raise exception 'HANDOFF_RECEIPT_PAYMENT_CHAIN_INVALID'; end if;
    return new;
  end if;
$branch$),
    ('assert_accepted_handoff_complete_v1',$branch$
  -- HANDOFF_RECEIPTS_V1
  if new.receipt_tracking then
    perform private.assert_handoff_receipt_chain_v1(new.id,new.receipt_worker_id,new.amount,new.receipt_received_amount,new.receipt_resolved_amount,new.receipt_outstanding_amount,new.company_ledger_entry_id);
    if new.receipt_outstanding_amount<>0 or not exists(select 1 from public.cash_handoff_items where handoff_id=new.id and released_at is null)
       or exists(select 1 from public.cash_handoff_items i left join public.arka_pending_payments p on p.id=i.pending_payment_id where i.handoff_id=new.id and (i.released_at is not null or p.id is null or p.status<>'ACCEPTED_BY_DISPATCH')) then raise exception 'HANDOFF_RECEIPT_FINAL_CHAIN_INVALID'; end if;
    return new;
  end if;
$branch$)
  ) as patches(name,body) loop
    select pg_get_functiondef(p.oid) into v_def from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='private' and p.proname=v_name and p.pronargs=0;
    if v_def is null then raise exception 'RECEIPT_REQUIRED_GUARD_MISSING:%',v_name; end if;
    if position('HANDOFF_RECEIPTS_V1' in v_def)=0 then
      v_at:=position(E'\nbegin\n' in v_def);
      if v_at=0 then raise exception 'RECEIPT_GUARD_INSERT_ANCHOR_MISSING:%',v_name; end if;
      execute overlay(v_def placing E'\nbegin\n'||v_branch from v_at for length(E'\nbegin\n'));
    end if;
  end loop;
end;
$patch$;

create or replace function private.record_cash_handoff_receipt_v1(
  p_actor_id uuid,p_handoff_id bigint,p_event_kind text,p_amount numeric,p_expected_outstanding numeric,p_reason text,p_note text,p_request_key text
) returns jsonb language plpgsql security definer set search_path=pg_catalog,public,private as $fn$
declare
  a public.users%rowtype; h public.cash_handoffs%rowtype; e public.cash_handoff_receipt_events%rowtype;
  w uuid; v_hash text; v_remaining numeric; v_received numeric; v_resolved numeric; v_ledger_id bigint;
  v_alloc record; v_bonus public.base_ready_bonuses%rowtype; v_previous_context text;
begin
  select * into a from public.users where id=p_actor_id and is_active is true;
  if not found or upper(coalesce(a.role,'')) not in ('DISPATCH','MASTER','MASTER USER','MASTER_USER','MASTERUSER','ADMIN','ADMIN_MASTER','OWNER','PRONAR','SUPERADMIN') then raise exception 'HANDOFF_RECEIPT_FORBIDDEN'; end if;
  if p_event_kind not in ('RECEIPT','RESOLUTION') or p_amount is null or p_amount::text in ('NaN','Infinity','-Infinity') or p_amount<0 or p_amount>10000000 or p_amount<>round(p_amount,2)
     or (p_event_kind='RESOLUTION' and p_amount=0) or p_expected_outstanding is null or p_expected_outstanding<=0 or p_expected_outstanding::text in ('NaN','Infinity','-Infinity') or p_expected_outstanding<>round(p_expected_outstanding,2)
     or p_amount>p_expected_outstanding then raise exception 'HANDOFF_RECEIPT_AMOUNT_INVALID'; end if;
  if p_request_key is null or p_request_key!~'^[A-Za-z0-9:_-]{12,120}$' then raise exception 'HANDOFF_RECEIPT_KEY_INVALID'; end if;
  if length(coalesce(p_note,''))>1000 or ((p_event_kind='RESOLUTION' or p_amount<p_expected_outstanding) and length(trim(coalesce(p_note,'')))<4) then raise exception 'HANDOFF_RECEIPT_REASON_REQUIRED'; end if;
  v_hash:=md5(jsonb_build_array(p_handoff_id,p_event_kind,p_amount,p_expected_outstanding,p_reason,trim(coalesce(p_note,'')))::text);
  perform pg_advisory_xact_lock(hashtext('HANDOFF_RECEIPT_REQUEST:'||a.id::text||':'||p_request_key));
  select * into h from public.cash_handoffs where id=p_handoff_id for update;
  if not found then raise exception 'HANDOFF_RECEIPT_NOT_PENDING'; end if;
  select * into e from public.cash_handoff_receipt_events where actor_id=a.id and request_key=p_request_key;
  if found then
    if e.payload_hash<>v_hash or e.handoff_id<>p_handoff_id then raise exception 'HANDOFF_RECEIPT_IDEMPOTENCY_CONFLICT'; end if;
    return jsonb_build_object('ok',true,'replayed',true,'handoff',to_jsonb(h),'event',to_jsonb(e));
  end if;
  if not exists(select 1 from public.cash_handoff_receipt_settings where id=1 and enabled) then raise exception 'HANDOFF_RECEIPT_WORKFLOW_PAUSED'; end if;
  if h.status<>'PENDING_DISPATCH_APPROVAL' then raise exception 'HANDOFF_RECEIPT_NOT_PENDING'; end if;
  select id into w from public.users where pin=h.worker_pin;
  if w is null then raise exception 'HANDOFF_RECEIPT_WORKER_MISSING'; end if;
  if w=a.id then raise exception 'HANDOFF_RECEIPT_SELF_APPROVAL'; end if;
  v_remaining:=case when h.receipt_tracking then h.receipt_outstanding_amount else h.amount end;
  if v_remaining<>p_expected_outstanding then raise exception 'HANDOFF_RECEIPT_STATE_CHANGED'; end if;
  if p_event_kind='RESOLUTION' and not h.receipt_tracking then raise exception 'HANDOFF_RECEIPT_RECORD_ACTUAL_FIRST'; end if;
  if exists(select 1 from public.company_budget_ledger where source_type='cash_handoff' and source_id=h.id) then raise exception 'HANDOFF_RECEIPT_LEGACY_LEDGER_EXISTS'; end if;
  perform 1 from public.arka_pending_payments p join public.cash_handoff_items i on i.pending_payment_id=p.id where i.handoff_id=h.id order by p.id for update of p;
  if not exists(select 1 from public.cash_handoff_items where handoff_id=h.id)
     or (select coalesce(sum(amount),0) from public.cash_handoff_items where handoff_id=h.id and released_at is null)<>h.amount
     or exists(select 1 from public.cash_handoff_items i left join public.arka_pending_payments p on p.id=i.pending_payment_id where i.handoff_id=h.id and (i.released_at is not null or p.id is null or p.status<>'PENDING_DISPATCH_APPROVAL')) then raise exception 'HANDOFF_RECEIPT_ITEMS_CHANGED'; end if;
  v_previous_context:=current_setting('tepiha.handoff_receipt_context',true);
  perform set_config('tepiha.handoff_receipt_context','on',true);
  insert into public.cash_handoff_receipt_events(handoff_id,worker_id,actor_id,actor_name,event_kind,amount,reason,note,outstanding_before,outstanding_after,request_key,payload_hash)
  values(h.id,w,a.id,a.name,p_event_kind,p_amount,coalesce(p_reason,''),trim(coalesce(p_note,'')),v_remaining,v_remaining-p_amount,p_request_key,v_hash) returning * into e;
  if p_event_kind='RECEIPT' and p_amount>0 then
    insert into public.company_budget_ledger(direction,amount,category,description,source_type,source_id,related_handoff_id,created_by_pin,created_by_name,approved_by_pin,approved_by_name)
    values('IN',p_amount,'WORKER_TO_DISPATCH','PRANIM REAL — '||coalesce(h.worker_name,'Punëtori')||' — DORËZIM #'||h.id,'cash_handoff_receipt',e.id,h.id,a.pin,a.name,a.pin,a.name) returning id into v_ledger_id;
    update public.cash_handoff_receipt_events set ledger_entry_id=v_ledger_id where id=e.id returning * into e;
    insert into public.company_budget_summary(id,current_balance,total_in,total_out) values(1,0,0,0) on conflict(id) do nothing;
    update public.company_budget_summary set current_balance=current_balance+p_amount,total_in=total_in+p_amount,updated_at=now() where id=1;
  end if;
  v_received:=h.receipt_received_amount+case when p_event_kind='RECEIPT' then p_amount else 0 end;
  v_resolved:=h.receipt_resolved_amount+case when p_event_kind='RESOLUTION' then p_amount else 0 end;
  -- Earned bonus deductions are confirmed once, independently of the shortage.
  if not h.receipt_tracking then
    for v_alloc in select * from public.base_ready_bonus_allocations where handoff_id=h.id and status='RESERVED' order by id for update loop
      update public.base_ready_bonus_allocations set status='RETAINED',updated_at=now() where id=v_alloc.id;
      update public.base_ready_bonuses set reserved_amount=round(greatest(0,reserved_amount-v_alloc.amount),2),retained_amount=round(retained_amount+v_alloc.amount,2),updated_at=now() where id=v_alloc.bonus_id returning * into v_bonus;
      perform public.base_ready_bonus_refresh_status_v1(v_alloc.bonus_id);
      update public.arka_pending_payments set handoff_note=case when v_bonus.remaining_amount<=0.005 then concat('READY_BONUS_RETAINED:',h.id,'|READY_BONUS:',v_bonus.id) else concat('READY_BONUS_OPEN:',v_bonus.id,'|RETAINED_IN_HANDOFF:',h.id,':',to_char(v_alloc.amount,'FM999999990.00')) end,updated_at=now() where id=v_bonus.arka_payment_id;
    end loop;
  end if;
  update public.cash_handoffs set receipt_tracking=true,receipt_worker_id=w,receipt_received_amount=v_received,receipt_resolved_amount=v_resolved,
    receipt_outstanding_amount=h.amount-v_received-v_resolved,receipt_updated_at=now(),company_ledger_entry_id=coalesce(h.company_ledger_entry_id,v_ledger_id),
    status=case when h.amount=v_received+v_resolved then 'ACCEPTED' else 'PENDING_DISPATCH_APPROVAL' end,
    decided_at=case when h.amount=v_received+v_resolved then now() else null end,dispatch_pin=a.pin,dispatch_name=a.name
  where id=h.id returning * into h;
  if h.status='ACCEPTED' then
    update public.arka_pending_payments p set status='ACCEPTED_BY_DISPATCH',approved_by_pin=a.pin,approved_by_name=a.name,handed_at=now(),handed_by_pin=a.pin,handed_by_name=a.name,handed_by_role=a.role,updated_at=now()
    from public.cash_handoff_items i where i.handoff_id=h.id and i.released_at is null and p.id=i.pending_payment_id;
  end if;
  perform set_config('tepiha.handoff_receipt_context',coalesce(v_previous_context,''),true);
  return jsonb_build_object('ok',true,'replayed',false,'handoff',to_jsonb(h),'event',to_jsonb(e));
end;
